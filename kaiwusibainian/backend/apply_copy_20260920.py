content = json.loads(CONTENT.read_text(encoding="utf-8"))

for n in content["process_nodes"]:
    nid = n["id"]
    if nid in SUMMARIES:
        n["summary"] = SUMMARIES[nid]
    if nid in DETAILS:
        n["details"] = DETAILS[nid]
    if nid in ("A1", "A3") and "E08" not in n.get("evidence_ids", []):
        n["evidence_ids"] = n.get("evidence_ids", []) + ["E08"]

for x in content["explanations"]:
    xid = x["id"]
    if xid in X_BODIES:
        x["body"] = X_BODIES[xid]
    if xid in ("X3", "X8", "X11") and "E08" not in x.get("source_refs", []):
        x["source_refs"] = x.get("source_refs", []) + ["E08"]

if not any(e["id"] == "E08" for e in content["evidence_sources"]):
    content["evidence_sources"].append(E08)

for e in content["evidence_sources"]:
    if e["id"] == "E05":
        e["note"] = E05_NOTE

CONTENT.write_text(json.dumps(content, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print("content.json updated")

# ---------------- 2) 同步更新 app.db（原地，不删库） ----------------
conn = sqlite3.connect(DB, timeout=30)
n_nodes = conn.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
if n_nodes == 0:
    print("app.db empty, skip db sync (下次启动 bat 会自动灌入)")
else:
    for n in content["process_nodes"]:
        conn.execute(
            "UPDATE nodes SET summary=?, details_json=?, evidence_ids_json=? WHERE id=?",
            (n["summary"], json.dumps(n["details"], ensure_ascii=False),
             json.dumps(n["evidence_ids"], ensure_ascii=False), n["id"]))
    for x in content["explanations"]:
        conn.execute(
            "UPDATE explanations SET body=?, source_refs_json=? WHERE id=?",
            (x["body"], json.dumps(x["source_refs"], ensure_ascii=False), x["id"]))
    conn.execute(
        "INSERT OR REPLACE INTO evidence (id,title,publisher,date,url,note) VALUES (?,?,?,?,?,?)",
        (E08["id"], E08["title"], E08["publisher"], E08["date"], E08["url"], E08["note"]))
    conn.execute("UPDATE evidence SET note=? WHERE id='E05'", (E05_NOTE,))
    conn.commit()
    print("app.db synced:", n_nodes, "nodes")
conn.close()
